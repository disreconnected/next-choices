// Builds every shipped artifact from src/. The outputs are committed (the
// SillyTavern extension loads ./index.js, Lumiverse installs from the repo and
// loads dist/*), so they are intentionally unminified and without sourcemaps.
//
//   src/st/index.ts            -> index.js          (iife, browser)   SillyTavern
//   src/lumiverse/frontend.ts  -> dist/frontend.js  (esm, browser)    Lumiverse
//   src/lumiverse/backend.ts   -> dist/backend.js   (esm, bun)        Lumiverse
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const targets = [
    {
        entry: 'src/st/index.ts',
        outdir: '.',
        name: 'index.js',
        format: 'iife',
        target: 'browser',
        banner: '// Generated by scripts/build.mjs from src/st/index.ts. Do not edit by hand.',
    },
    { entry: 'src/lumiverse/frontend.ts', outdir: 'dist', name: 'frontend.js', format: 'esm', target: 'browser' },
    { entry: 'src/lumiverse/backend.ts', outdir: 'dist', name: 'backend.js', format: 'esm', target: 'bun' },
];

let failed = false;
for (const { entry, outdir, name, format, target, banner } of targets) {
    const result = await Bun.build({
        entrypoints: [resolve(root, entry)],
        outdir: resolve(root, outdir),
        naming: name,
        format,
        target,
        minify: false,
        sourcemap: 'none',
        ...(banner ? { banner } : {}),
    });
    if (!result.success) {
        failed = true;
        console.error(`FAILED ${entry}`);
        for (const log of result.logs) console.error(String(log));
        continue;
    }
    for (const output of result.outputs) {
        console.log(`${entry} -> ${output.path.slice(root.length + 1).replaceAll('\\', '/')} (${output.size} bytes)`);
    }
}

if (failed) process.exit(1);
